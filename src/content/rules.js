'use strict';
// 合规规则（2026-10-21 按法规重新整理，不沿用任何旧词表）
//
// 依据：
//   《广告法》第 9 条     不得使用「国家级」「最高级」「最佳」等用语
//   《广告法》第 17 条    除医疗、药品、医疗器械广告外，任何广告不得涉及疾病治疗功能，不得使用医疗用语
//   《广告法》第 18 条    保健食品广告不得表示功效、安全性的断言或保证
//   《食品安全法》第 73 条 食品广告不得涉及疾病预防、治疗功能
//   平台规则             「诱导分享/关注」、虚构权威背书属于违规
//
// 公众号科普文严格说不是广告，但平台审核和投诉都按这些尺度来。所以：
//   error  一出现就不让推草稿（明确的疗效断言、极限词、诱导、伪权威）
//   warn   提示人工看一眼（语境决定是否违规，比如「药」字在「药店」里没问题）
//
// 每条规则：{ id, level, re, why, allow? }
//   re    正则（全局匹配）
//   allow 命中后如果所在片段匹配 allow，就放过

const R = (id, level, re, why, allow) => ({ id, level, re, why, allow });

const RULES = [
  // ── 疾病治疗 / 预防断言（广告法 17、食品安全法 73） ──
  R('cure', 'error', /(治疗|治愈|根治|痊愈|治好|医好|药到病除|包治)/g, '疾病治疗用语'),
  R('prevent', 'error', /(预防|防止|防治|远离)(癌|肿瘤|糖尿病|高血压|心脏病|中风|脑梗|痛风|骨质疏松|老年痴呆|感冒)/g, '宣称预防具体疾病'),
  R('lower', 'error', /(降|调节|控制)(血压|血糖|血脂|尿酸|三高|胆固醇)/g, '宣称调节生理指标'),
  R('anticancer', 'error', /(抗癌|防癌|抑癌|杀死癌细胞)/g, '抗癌类断言'),
  R('organ', 'error', /(补肾|壮阳|护肝|养肝|排毒|清肠|养胃|健脾|润肺|清肺)/g, '脏器功效断言（中医养生常见，但属功效宣称）'),
  R('killbug', 'error', /(杀菌|消炎|抗病毒|抗菌|消肿)/g, '医疗功效用语'),

  // ── 保健功能声称（只有注册保健食品可以用，且不能断言；普通内容不要用） ──
  R('health-claim', 'error', /(增强|提高|提升)(免疫力|抵抗力)|(改善|治疗)(睡眠|失眠)|延缓衰老|抗衰老|抗氧化|抗疲劳|缓解(体力)?疲劳|美容养颜|祛斑|减肥|瘦身|燃脂|丰胸|增高/g, '保健功能声称'),

  // ── 效果保证（广告法 18、28） ──
  R('guarantee', 'error', /(\d+|[一二三四五六七八九十]+)\s*(天|周|个月)\s*(见效|好转|治好|根除|瘦)|立竿见影|立刻见效|马上见效|永不复发|无效退款|无副作用|零副作用|百分之百|100\s*%/g, '效果或安全性保证'),

  // ── 极限用语（广告法 9） ──
  R('superlative', 'error', /国家级|世界级|最高级|顶级|极品|顶尖|独家|首选|第一品牌|全网第一|全国第一|史上最|万能|神药|神器|特效/g, '极限用语'),
  R('zui', 'warn', /最(好|佳|强|优|有效|管用|健康|安全|科学|正确)/g, '「最 X」绝对化用语，确认不是在夸效果', /最好(别|不要|不|先|还是|能)/),
  R('diyi', 'warn', /第一(名|位|选择|好)/g, '「第一」可能被认定为极限用语'),

  // ── 药品、处方（可能构成医疗建议） ──
  R('drug', 'warn', /(药方|偏方|秘方|处方|疗程|停药|服药|吃药|用药)/g, '涉及用药，确认没有给出用药建议'),

  // ── 伪权威背书（广告法 16、28） ──
  R('authority', 'error', /(专家|医生|医师|教授|院士|国医大师)(推荐|力荐|都在用|认证)|央视推荐|国家认证|卫健委推荐/g, '虚构或借用权威背书'),

  // ── 诱导分享 / 关注（平台运营规范） ──
  R('induce', 'error', /(转发|分享)(给|到)?.{0,6}(才能|就能|即可|否则)|不转不是|必须转发|转发(有|领)|关注(后|即可)?(领|送|抽)|点赞(后|即可)?(领|送)/g, '诱导分享或关注'),

  // ── 恐吓标题（平台「标题党」规范，warn） ──
  R('scare', 'warn', /(赶紧|马上)(扔|停)|会死|致癌|害死|毁了你|千万别|震惊|吓人/g, '恐吓或夸张措辞，平台容易判标题党'),
];

/**
 * @param {string} text 纯文本
 * @param {string} where 标签（标题/摘要/正文），用于报告
 * @returns {{level, id, why, hit, where, context}[]}
 */
function scan(text, where = '正文') {
  const out = [];
  for (const r of RULES) {
    r.re.lastIndex = 0;
    let m;
    while ((m = r.re.exec(text))) {
      const s = Math.max(0, m.index - 8);
      const context = text.slice(s, m.index + m[0].length + 8).replace(/\s+/g, ' ');
      if (r.allow && r.allow.test(text.slice(m.index, m.index + m[0].length + 4))) continue;
      out.push({ level: r.level, id: r.id, why: r.why, hit: m[0], where, context });
    }
  }
  return out;
}

module.exports = { RULES, scan };
